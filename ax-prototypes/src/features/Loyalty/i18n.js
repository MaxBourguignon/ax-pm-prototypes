function readLang() {
  try { return localStorage.getItem(STORAGE_KEY) || 'fr'; } catch { return 'fr'; }
}

export function useLang() {
  const [lang, setLangState] = React.useState(readLang);

  React.useEffect(() => {
    const sync = () => setLangState(readLang());
    window.addEventListener(EVENT, sync);
    return () => window.removeEventListener(EVENT, sync);
  }, []);

  const setLang = React.useCallback((l) => {
    try { localStorage.setItem(STORAGE_KEY, l); } catch { /* storage unavailable */ }
    setLangState(l);
    window.dispatchEvent(new Event(EVENT));
  }, []);

  const t = React.useCallback((key, vars) => {
    let s = STR[lang]?.[key] ?? STR.fr[key] ?? key;
    if (vars) Object.entries(vars).forEach(([k, v]) => { s = s.replaceAll(`{${k}}`, v); });
    return s;
  }, [lang]);

  const tr = React.useCallback((v) => (v && typeof v === 'object' ? (v[lang] ?? v.fr) : v), [lang]);
  const fmt = React.useCallback((n) => Number(n).toLocaleString(lang === 'fr' ? 'fr-BE' : 'en-GB'), [lang]);

  return { lang, setLang, t, tr, fmt };
}

export default useLang;
