const LANG = 'en';

export function useLang() {
  const t = React.useCallback((key, vars) => {
    let s = STR[LANG][key] ?? key;
    if (vars) Object.entries(vars).forEach(([k, v]) => { s = s.replaceAll(`{${k}}`, v); });
    return s;
  }, []);
  const tr  = React.useCallback((v) => (v && typeof v === 'object' ? (v[LANG] ?? v.fr) : v), []);
  const fmt = React.useCallback((n) => Number(n).toLocaleString('en-GB'), []);
  return { lang: LANG, t, tr, fmt };
}

export default useLang;
