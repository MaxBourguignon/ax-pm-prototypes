// ── Icon button ────────────────────────────────────────────────────────────────
function IconBtn({ children, title }) {
  const [hovered, setHovered] = useState(false);
  return (
    <button
      title={title}
      onMouseEnter={() => setHovered(true)}
      onMouseLeave={() => setHovered(false)}
      style={{
        width: 40, height: 40, borderRadius: 10, flexShrink: 0,
        display: 'flex', alignItems: 'center', justifyContent: 'center',
        background: hovered ? '#EEF3FF' : 'transparent',
        border: '1px solid transparent',
        cursor: 'pointer', transition: `all ${DS.durFast} ${DS.ease}`,
      }}
    >
      {children}
    </button>
  );
}

// ── Breadcrumb ───────────────────────────────────────────────────────────────
function Breadcrumb() {
  const { pathname } = useLocation();
  const segments = pathname.split('/').filter(Boolean);

  return (
    <div style={{ display: 'flex', alignItems: 'center', gap: 6, minWidth: 0, fontFamily: DS.ff }}>
      <Link to="/home" title="Home"
        style={{ display: 'flex', alignItems: 'center', justifyContent: 'center', width: 34, height: 34, borderRadius: 9, textDecoration: 'none' }}>
        <IconHome c={segments.length === 0 ? ACCENT : '#8A93A6'} />
      </Link>
      {segments.map((seg, i) => {
        const isLast = i === segments.length - 1;
        const to = '/' + segments.slice(0, i + 1).join('/');
        return (
          <React.Fragment key={to}>
            <IconChevron c="#C2CAD6" />
            <Link to={to}
              style={{
                fontSize: 15,
                fontWeight: isLast ? 600 : 500,
                color: isLast ? ACCENT : '#5A6273',
                textDecoration: 'none',
                whiteSpace: 'nowrap',
              }}>
              {labelFor(seg)}
            </Link>
          </React.Fragment>
        );
      })}
    </div>
  );
}

